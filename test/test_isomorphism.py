def face_indices(m):
    r"""
    Return the list that gives to each half-edge of ``m`` the index of its
    face (distinct per face).
    """
    data = [-1] * len(m.vertex_permutation())
    for i, face in enumerate(m.faces()):
        for h in face:
            data[h] = i
    return data


